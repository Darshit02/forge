import { Hono } from "hono";
import { zValidator } from "@hono/zod-validator";
import { z } from "zod";
import { eq, and, asc } from "drizzle-orm";
import { requireAuth, requireProjectOwner } from "../middleware/auth.js";
import { db } from "../db/client.js";
import { apiRequests, collections } from "../db/schema.js";
import { NotFoundError } from "../utils/errors.js";

import {
  CreateCollectionRequestSchema,
  UpdateCollectionRequestSchema,
  CreateApiRequestRequestSchema,
  UpdateApiRequestRequestSchema,
} from "@forge/shared";

export const collectionsRoutes = new Hono();

collectionsRoutes.use("*", requireAuth);

/**
 * GET /api/projects/:id/collections - List collections with their requests
 */
collectionsRoutes.get("/projects/:id/collections", requireProjectOwner, async (c) => {
  const projectId = c.req.param("id")!;

  const colls = await db
    .select()
    .from(collections)
    .where(eq(collections.projectId, projectId))
    .orderBy(asc(collections.orderIndex));

  const reqs = await db
    .select()
    .from(apiRequests)
    .where(eq(apiRequests.projectId, projectId))
    .orderBy(asc(apiRequests.createdAt));

  // Nest requests inside collections
  const result = colls.map((coll) => ({
    ...coll,
    requests: reqs.filter((r) => r.collectionId === coll.id),
  }));

  return c.json({ collections: result });
});

/**
 * POST /api/projects/:id/collections - Create collection folder
 */
collectionsRoutes.post(
  "/projects/:id/collections",
  requireProjectOwner,
  zValidator("json", CreateCollectionRequestSchema),
  async (c) => {
    const projectId = c.req.param("id")!;
    const { name, parentId } = c.req.valid("json");

    const [created] = await db
      .insert(collections)
      .values({
        projectId,
        name: name.trim(),
        parentId: parentId || null,
      })
      .returning();

    return c.json({ collection: created }, 201);
  }
);

/**
 * PATCH /api/collections/:id - Update collection
 */
collectionsRoutes.patch(
  "/collections/:id",
  zValidator("json", UpdateCollectionRequestSchema),
  async (c) => {
    const collectionId = c.req.param("id")!;
    const body = c.req.valid("json");

    const [updated] = await db
      .update(collections)
      .set({
        ...(body.name ? { name: body.name.trim() } : {}),
        ...(body.orderIndex !== undefined ? { orderIndex: body.orderIndex } : {}),
      })
      .where(eq(collections.id, collectionId))
      .returning();

    if (!updated) {
      throw new NotFoundError("Collection not found");
    }

    return c.json({ collection: updated });
  }
);

/**
 * DELETE /api/collections/:id - Delete collection
 */
collectionsRoutes.delete("/collections/:id", async (c) => {
  const collectionId = c.req.param("id")!;

  const [deleted] = await db
    .delete(collections)
    .where(eq(collections.id, collectionId))
    .returning({ id: collections.id });

  if (!deleted) {
    throw new NotFoundError("Collection not found");
  }

  return c.json({ ok: true, id: deleted.id });
});

/**
 * POST /api/collections/:id/requests - Create request inside collection
 */
collectionsRoutes.post(
  "/collections/:id/requests",
  zValidator("json", CreateApiRequestRequestSchema),
  async (c) => {
    const collectionId = c.req.param("id")!;
    const body = c.req.valid("json");

    const [collection] = await db
      .select({ projectId: collections.projectId })
      .from(collections)
      .where(eq(collections.id, collectionId))
      .limit(1);

    if (!collection) {
      throw new NotFoundError("Collection not found");
    }

    const [created] = await db
      .insert(apiRequests)
      .values({
        projectId: collection.projectId,
        collectionId,
        name: body.name.trim(),
        method: body.method.toUpperCase(),
        path: body.path,
        headers: body.headers || {},
        body: body.body || {},
        authConfig: body.authConfig || {},
        autoGenerated: false, // User manually created this
      })
      .returning();

    return c.json({ request: created }, 201);
  }
);

/**
 * PATCH /api/requests/:id - Update saved request
 */
collectionsRoutes.patch(
  "/requests/:id",
  zValidator("json", UpdateApiRequestRequestSchema),
  async (c) => {
    const requestId = c.req.param("id")!;
    const body = c.req.valid("json");

    const [updated] = await db
      .update(apiRequests)
      .set({
        ...(body.name ? { name: body.name.trim() } : {}),
        ...(body.method ? { method: body.method.toUpperCase() } : {}),
        ...(body.path ? { path: body.path } : {}),
        ...(body.headers !== undefined ? { headers: body.headers } : {}),
        ...(body.body !== undefined ? { body: body.body } : {}),
        ...(body.authConfig !== undefined ? { authConfig: body.authConfig } : {}),
        autoGenerated: false, // Mark user-edited to preserve during spec sync!
        updatedAt: new Date(),
      })
      .where(eq(apiRequests.id, requestId))
      .returning();

    if (!updated) {
      throw new NotFoundError("API request not found");
    }

    return c.json({ request: updated });
  }
);

/**
 * DELETE /api/requests/:id - Delete saved request
 */
collectionsRoutes.delete("/requests/:id", async (c) => {
  const requestId = c.req.param("id")!;

  const [deleted] = await db
    .delete(apiRequests)
    .where(eq(apiRequests.id, requestId))
    .returning({ id: apiRequests.id });

  if (!deleted) {
    throw new NotFoundError("API request not found");
  }

  return c.json({ ok: true, id: deleted.id });
});
