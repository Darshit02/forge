export type ProjectLanguage = "python" | "node" | "typescript" | "go" | "rust";

export type ProjectFramework =
  | "fastapi"
  | "flask"
  | "django"
  | "express"
  | "nestjs"
  | "hono"
  | "fastify"
  | "fiber"
  | "gin"
  | "axum";

export type ProjectStatus =
  | "stopped"
  | "starting"
  | "running"
  | "error"
  | "building";

export type AIProviderType = "openai" | "anthropic" | "google" | "custom";

export type ChatRole = "user" | "assistant" | "system" | "tool";

export type ChatMode = "chat" | "edit" | "agent";

export interface User {
  id: string;
  email: string;
  name: string | null;
}

export interface AuthResponse {
  user: User;
  accessToken: string;
}

export interface AIProvider {
  id: string;
  provider: AIProviderType;
  label: string;
  maskedKey: string;
  baseUrl: string | null;
  modelDefault: string;
  isDefault: boolean;
  createdAt?: string;
}

export interface Project {
  id: string;
  userId: string;
  name: string;
  description: string | null;
  language: ProjectLanguage;
  framework: ProjectFramework;
  status: ProjectStatus;
  hostPort: number | null;
  containerId: string | null;
  workspacePath: string;
  aiProviderId: string | null;
  lastStartedAt: string | null;
  createdAt: string;
  updatedAt: string;
}

export interface TemplateMetadata {
  id: ProjectFramework;
  name: string;
  language: ProjectLanguage;
  description: string;
  defaultPort: number;
  openApiEndpoints: string[];
}

export interface FileTreeNode {
  name: string;
  path: string; // relative to workspace root
  type: "file" | "directory";
  size?: number;
  children?: FileTreeNode[];
}

export interface FileContent {
  path: string;
  content: string;
  size: number;
  updatedAt: string;
}

export interface ContainerStatusInfo {
  status: ProjectStatus;
  containerId: string | null;
  hostPort: number | null;
  uptimeSeconds?: number;
}

export interface Collection {
  id: string;
  projectId: string;
  name: string;
  parentId: string | null;
  orderIndex: number;
  createdAt: string;
  requests?: APIRequest[];
}

export interface APIRequest {
  id: string;
  collectionId: string | null;
  projectId: string;
  name: string;
  method: string;
  path: string;
  headers: Record<string, string>;
  body: unknown;
  authConfig: Record<string, unknown>;
  autoGenerated: boolean;
  lastResponse?: TestResponsePayload;
  createdAt: string;
  updatedAt: string;
}

export interface TestRequestPayload {
  method: string;
  path: string;
  headers?: Record<string, string>;
  body?: unknown;
  environmentId?: string;
  requestId?: string;
}

export interface TestResponsePayload {
  status: number;
  headers: Record<string, string>;
  body: unknown;
  durationMs: number;
}

export interface TestHistoryItem {
  id: string;
  projectId: string;
  requestId: string | null;
  method: string;
  path: string;
  statusCode: number;
  durationMs: number;
  responseSnippet: unknown;
  ranAt: string;
}

export interface ToolCallExecution {
  toolCallId: string;
  toolName: "writeFile" | "deleteFile" | "readFile" | "runCommand";
  args: Record<string, unknown>;
  result?: unknown;
}

export interface ChatSession {
  id: string;
  projectId: string;
  title: string;
  createdAt: string;
}

export interface ChatMessage {
  id: string;
  sessionId: string;
  role: ChatRole;
  content: string;
  toolCalls?: ToolCallExecution[] | null;
  createdAt: string;
}

export interface Environment {
  id: string;
  projectId: string;
  name: string;
  variables: Record<string, string>;
  isActive: boolean;
  createdAt: string;
}

export type WSServerMessage =
  | { type: "container.status"; status: ProjectStatus }
  | { type: "container.log"; line: string }
  | { type: "spec.updated"; spec: Record<string, unknown> }
  | { type: "file.changed"; path: string; content?: string }
  | { type: "ai.token"; delta: string }
  | { type: "ai.done"; messageId: string }
  | { type: "test.result"; requestId?: string; response: TestResponsePayload }
  | { type: "error"; error: string };
